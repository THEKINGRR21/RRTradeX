"use client";
import clsx from "clsx";
import { useEffect, type ReactNode } from "react";

const inr = new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", minimumFractionDigits: 2, maximumFractionDigits: 2 });
const inr0 = new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 0 });
const num = new Intl.NumberFormat("en-IN");
export const fmtINR = (v: string | number | null | undefined, compact = false) => (v == null || v === "" ? "—" : compact ? inr0.format(Number(v)) : inr.format(Number(v)));
export const fmtNum = (v: string | number | null | undefined) => (v == null ? "—" : num.format(Number(v)));
export const fmtQty = (v: string | number) => num.format(Number(v));
export const fmtTime = (iso?: string | null, withDate = true) =>
  iso ? new Date(iso).toLocaleString("en-IN", { timeZone: "Asia/Kolkata", hour: "2-digit", minute: "2-digit", second: withDate ? undefined : "2-digit", ...(withDate ? { day: "2-digit", month: "short" } : {}) }) + " IST" : "—";
export const fmtDate = (iso?: string | null) => (iso ? new Date(iso).toLocaleDateString("en-IN", { timeZone: "Asia/Kolkata", day: "2-digit", month: "short", year: "numeric" }) : "—");

export function Signed({ v, children, className }: { v: string | number | null | undefined; children?: ReactNode; className?: string }) {
  const n = Number(v ?? 0);
  return <span className={clsx("num", n > 0 ? "text-gain" : n < 0 ? "text-loss" : "text-mist-300", className)}>{children ?? (n > 0 ? "+" : "") + fmtINR(v)}</span>;
}
export function Pct({ v, className }: { v: string | number | null | undefined; className?: string }) {
  if (v == null) return <span className="text-mist-500">—</span>;
  const n = Number(v);
  return <span className={clsx("num", n > 0 ? "text-gain" : n < 0 ? "text-loss" : "text-mist-300", className)}>{n > 0 ? "▲" : n < 0 ? "▼" : ""} {Math.abs(n).toFixed(2)}%</span>;
}

const FEED: Record<string, string> = {
  live: "bg-gain-soft text-gain", delayed: "bg-sky-950 text-sky-300", simulated: "bg-brand-soft text-brand",
  stale: "bg-orange-950 text-orange-300", unavailable: "bg-loss-soft text-loss",
};
/** Source, timestamp and freshness label shown next to every price (FR-MKT-04, §7.1). */
export function QuoteMeta({ q, compact }: { q?: { feedStatus: string; source?: string; quotedAt?: string; ageSeconds?: number } | null; compact?: boolean }) {
  if (!q) return <span className={clsx("chip", FEED.unavailable)}>unavailable</span>;
  return (
    <span className="inline-flex flex-wrap items-center gap-1.5 text-[11px] text-mist-400">
      <span className={clsx("chip uppercase", FEED[q.feedStatus] ?? FEED.unavailable)} title={q.feedStatus === "simulated" ? "Generated by the RRTradeX simulator — not real exchange data" : undefined}>{q.feedStatus}</span>
      {!compact && <span>{q.source} · {fmtTime(q.quotedAt, false)}</span>}
    </span>
  );
}

